/**
 * Geohash → relay resolution, matching Amethyst's approach: each location
 * channel uses the ~5 relays geographically nearest its cell center, so a
 * channel only connects to the relays it's actually on instead of the user's
 * whole relay list. The directory is a small geographically-spread built-in
 * list (attribution: permissionlesstech/georelays) — deterministic and
 * cross-client stable (ties broken by host ascending).
 */
object GeohashRelays {

    private const val DEFAULT_COUNT = 5
    private const val EARTH_RADIUS_KM = 6371.0

    private data class GeoRelay(val host: String, val relay: String, val latitude: Double, val longitude: Double)

    /** The relays nearest [geohash]'s center (wss:// URLs), max [count]. */
    fun closestRelays(geohash: String, count: Int = DEFAULT_COUNT): List<String> {
        val decoded = Geohash.decode(geohash) ?: return emptyList()
        return closest(decoded.latitude, decoded.longitude, FALLBACK, count)
    }

    /**
     * The geohash values to subscribe to for a channel: the channel code plus
     * its parent prefixes down to 4 chars, longest first.
     *
     * Relay #g filters match EXACTLY, but geohashes are hierarchical — a
     * message posted to a 5-char city cell (Bitchat's default level) lives
     * inside our 6-char neighborhood cell. Subscribing to the prefixes lets us
     * see messages posted at any coarser precision (city / province / region)
     * instead of only the exact code. Matches how the other clients actually
     * talk: Bitchat tags with its level's geohash, so this is what makes other
     * users' messages visible.
     */
    fun watchGeohashes(code: String): List<String> {
        val valid = code.lowercase().filter { it in "0123456789bcdefghjkmnpqrstuvwxyz" }
        if (valid.length < 4) return listOf(valid)
        return (4..valid.length).map { valid.take(it) }.reversed()
    }

    /**
     * The geohash values to TAG an outgoing message with: the channel code and,
     * when it's finer than city level, the 5-char city prefix — so Bitchat and
     * Amethyst users watching the city cell see our message too.
     */
    fun postGeohashes(code: String): List<String> {
        val valid = code.lowercase().filter { it in "0123456789bcdefghjkmnpqrstuvwxyz" }
        val out = mutableListOf(valid)
        if (valid.length > 5) out.add(valid.take(5))
        return out.distinct()
    }

    private fun closest(lat: Double, lon: Double, relays: List<GeoRelay>, count: Int): List<String> =
        relays
            .map { it to haversineKm(lat, lon, it.latitude, it.longitude) }
            .sortedWith(compareBy({ it.second }, { it.first.host }))
            .map { it.first.relay }
            .distinct()
            .take(count)

    private fun haversineKm(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val dLat = (lat2 - lat1).toRadians()
        val dLon = (lon2 - lon1).toRadians()
        val a = sin(dLat / 2) * sin(dLat / 2) +
            cos(lat1.toRadians()) * cos(lat2.toRadians()) * sin(dLon / 2) * sin(dLon / 2)
        return 2 * EARTH_RADIUS_KM * asin(min(1.0, sqrt(a)))
    }

    private fun Double.toRadians(): Double = this / 180.0 * PI

